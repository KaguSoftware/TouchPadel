#!/usr/bin/env node
/**
 * Render the Touch Padel site's brand assets for apps/web from the brand's own
 * vectors (see brand-render-kit.mjs for where each shape comes from), with
 * Playwright's cached Chromium and the real Lama Sans.
 *
 *   node packages/ui/scripts/render-site-assets.mjs              site set + café set
 *   node packages/ui/scripts/render-site-assets.mjs --only=site  just the site set
 *   node packages/ui/scripts/render-site-assets.mjs --only=cafe  just the café set
 *   node packages/ui/scripts/render-site-assets.mjs --badges     also re-download the
 *                                                               official store badges
 *
 * Site set (apps/web/public/brand/site/):
 *   favicon.svg              the ball (green felt, white seams) on a Touch Blue rounded tile
 *   icon-192.png, icon-512.png   the same tile, transparent corners (manifest, purpose any)
 *   icon-512-maskable.png    full-bleed Touch Blue, the ball inside the 80 % safe circle
 *   apple-icon-180.png       full-bleed and opaque (iOS applies its own mask)
 *   og-touch-padel-en.png    1200x630 share poster: navy field, a Touch Blue block of
 *   og-touch-padel-ar.png    green court-line bands, the white lockup, the two-weight
 *                            headline from site.hero (heavy line in green)
 *
 * Café set: see render-cafe-icons.mjs.
 *
 * Store badges (apps/web/public/brand/stores/, only with --badges): the official
 * artwork, downloaded and checked, never drawn. Apple's badge service moved from
 * tools.applemarketingtools.com (no longer resolves) to
 * toolbox.marketingtools.apple.com; its Arabic badge is under the locale `ar-ar`.
 */
import path from 'node:path';
import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import {
  ROOT,
  C,
  BRAND_FAMILY,
  fontFaceCss,
  lockupSvg,
  ballDiameterAt,
  ballGroup,
  patternSvg,
  svgPage,
  withBrowser,
} from './brand-render-kit.mjs';
import { renderCafe } from './render-cafe-icons.mjs';

const SITE_OUT = path.join(ROOT, 'apps', 'web', 'public', 'brand', 'site');
const STORES_OUT = path.join(ROOT, 'apps', 'web', 'public', 'brand', 'stores');

const catalog = (f) => import(pathToFileURL(path.join(ROOT, 'packages', 'i18n', 'src', 'catalogs', f)).href);
const { siteEn } = await catalog('site.en.ts');
const { siteAr } = await catalog('site.ar.ts');

// ---------------------------------------------------------------------------
// Icons
// ---------------------------------------------------------------------------

/**
 * The favicon: the ball alone, the brand's small mark (style reference 2.4),
 * on a Touch Blue tile. Drawn on a 64 grid so a 16 px tab gets whole-pixel
 * geometry at 4:1; the ball fills 48/64 of the tile, the most it can while the
 * blue still reads as a tile around it.
 */
const faviconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64">
<title>Touch Padel</title>
<!-- Generated by packages/ui/scripts/render-site-assets.mjs from logoPaths.ts; do not edit by hand. -->
<rect width="64" height="64" rx="14" fill="${C.blue}"/>
${ballGroup({ cx: 32, cy: 32, d: 48 })}
</svg>
`;

/** A full-bleed square of Touch Blue with the ball at `ratio` of its side. */
const fieldSvg = (size, ratio) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">` +
  `<rect width="${size}" height="${size}" fill="${C.blue}"/>` +
  ballGroup({ cx: size / 2, cy: size / 2, d: size * ratio }) +
  `</svg>`;

// ---------------------------------------------------------------------------
// Share poster
// ---------------------------------------------------------------------------

const W = 1200;
const H = 630;
/** Outer margin; also comfortably more than one ball diameter of clear space round the lockup. */
const M = 72;
const LOCKUP_H = 108;
/** The pattern block's width, bled off the top, bottom and inline end. */
const BLOCK_W = 420;

/**
 * The block's crop of the pattern panel. Scale 2.4 puts the board's 16-unit
 * band at 38 px (a poster weight, style reference 5.1) and the offset picks
 * the stretch of the panel where the bands cross each other in an open X
 * rather than bunching at one edge. Same crop in both languages: the pattern
 * is abstract and never mirrored; only the block moves to the inline end.
 */
const CROP = { scale: 2.4, x: -120, y: -105 };

function posterPage({ locale, fonts }) {
  const ar = locale === 'ar';
  const hero = ar ? siteAr.hero : siteEn.hero;
  const pattern = patternSvg({ width: BLOCK_W, height: H, ...CROP, color: C.green, opacity: 1 });
  const lockup = lockupSvg({ tone: 'onDark', height: LOCKUP_H, id: `sw-${locale}` });
  return `<!doctype html><html lang="${locale}" dir="${ar ? 'rtl' : 'ltr'}"><head><meta charset="utf-8"><style>
  ${fonts}
  html,body{margin:0}
  body{width:${W}px;height:${H}px;overflow:hidden;position:relative;background:${C.navy};color:${C.white};font-family:'${BRAND_FAMILY}',sans-serif}
  .block{position:absolute;inset-block:0;inset-inline-end:0;inline-size:${BLOCK_W}px;background:${C.blue};overflow:hidden}
  .block svg{display:block}
  .lockup{position:absolute;inset-block-start:${M - 8}px;inset-inline-start:${M}px}
  .lockup svg{display:block}
  h1{position:absolute;margin:0;inset-inline-start:${M}px;inset-block-end:${M - 6}px;inline-size:${W - BLOCK_W - 2 * M + 40}px;font-weight:900;font-feature-settings:'tnum'}
  h1 span{display:block}
  h1 .one{font-weight:400}
  h1 .two{color:${C.green}}
  [dir='ltr'] h1{font-size:112px;line-height:.92;letter-spacing:-.02em;text-transform:uppercase}
  [dir='rtl'] h1{font-size:128px;line-height:1.3}
</style></head><body>
<div class="block" aria-hidden="true">${pattern}</div>
<div class="lockup">${lockup}</div>
<h1><span class="one">${hero.lineOne}</span><span class="two">${hero.lineTwo}</span></h1>
</body></html>`;
}

// ---------------------------------------------------------------------------
// Store badges
// ---------------------------------------------------------------------------

const BADGES = [
  ['app-store-en.svg', 'https://toolbox.marketingtools.apple.com/api/v2/badges/download-on-the-app-store/black/en-us'],
  ['app-store-ar.svg', 'https://toolbox.marketingtools.apple.com/api/v2/badges/download-on-the-app-store/black/ar-ar'],
  ['google-play-en.png', 'https://play.google.com/intl/en_us/badges/static/images/badges/en_badge_web_generic.png'],
  ['google-play-ar.png', 'https://play.google.com/intl/en_us/badges/static/images/badges/ar_badge_web_generic.png'],
];

/** Download each badge and refuse anything that is not the file type it claims to be. */
async function fetchBadges() {
  await fs.mkdir(STORES_OUT, { recursive: true });
  for (const [file, url] of BADGES) {
    const res = await fetch(url, { redirect: 'follow' });
    if (!res.ok) throw new Error(`${file}: ${url} answered ${res.status}; not writing a badge`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (file.endsWith('.svg')) {
      const text = buf.toString('utf8');
      if (!/^\s*(<\?xml[^>]*>\s*)?<svg[\s>]/.test(text)) throw new Error(`${file}: not an SVG`);
      if (/<script|<foreignObject|\son\w+\s*=|href\s*=|<image|@import|url\(/i.test(text)) {
        throw new Error(`${file}: SVG carries active or external content; refusing`);
      }
    } else {
      const sig = buf.subarray(0, 8).toString('hex');
      if (sig !== '89504e470d0a1a0a') throw new Error(`${file}: not a PNG`);
      console.log(`  ${file}: ${buf.readUInt32BE(16)}x${buf.readUInt32BE(20)}`);
    }
    await fs.writeFile(path.join(STORES_OUT, file), buf);
    console.log('wrote', path.relative(ROOT, path.join(STORES_OUT, file)), `(${buf.length} B)`);
  }
}

// ---------------------------------------------------------------------------

async function renderSite(shot) {
  // House rule (style reference 2.4): one ball diameter of clear space round the lockup.
  if (M - 8 < ballDiameterAt(LOCKUP_H)) throw new Error('poster margin is under one ball diameter');
  await fs.mkdir(SITE_OUT, { recursive: true });
  await fs.writeFile(path.join(SITE_OUT, 'favicon.svg'), faviconSvg);
  console.log('wrote', path.relative(ROOT, path.join(SITE_OUT, 'favicon.svg')));
  const out = (f) => path.join(SITE_OUT, f);
  await shot(svgPage(faviconSvg, 192), 192, 192, out('icon-192.png'), { transparent: true });
  await shot(svgPage(faviconSvg, 512), 512, 512, out('icon-512.png'), { transparent: true });
  // Safe zone: a circle of 40 % radius. The ball's diameter is half the side, well inside it.
  await shot(svgPage(fieldSvg(512, 0.5), 512), 512, 512, out('icon-512-maskable.png'));
  await shot(svgPage(fieldSvg(180, 0.62), 180), 180, 180, out('apple-icon-180.png'));

  const fonts = await fontFaceCss([400, 900]);
  await shot(posterPage({ locale: 'en', fonts }), W, H, out('og-touch-padel-en.png'));
  await shot(posterPage({ locale: 'ar', fonts }), W, H, out('og-touch-padel-ar.png'));
}

const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7);
const parts = only ? only.split(',') : ['site', 'cafe'];
if (process.argv.includes('--badges') || parts.includes('badges')) await fetchBadges();
if (parts.includes('site') || parts.includes('cafe')) {
  await withBrowser(async (shot) => {
    if (parts.includes('site')) await renderSite(shot);
    if (parts.includes('cafe')) await renderCafe(shot);
  });
}
